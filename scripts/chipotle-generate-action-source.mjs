/**
 * Regenerates `lib/key-release/chipotle-action-source.ts` from
 * `lib/key-release/chipotle-action.js`.
 *
 * The browser needs the action's source as a string, not a file path, to
 * submit as the cache-miss retry's `code` (see `chipotle.ts`,
 * `invokeActionWithCacheMissRetry` — docs/stories/H-69.md's amendments). This
 * repo has no raw-text bundler loader configured, and adding one is more
 * moving parts than a generated constant plus a byte-for-byte equality check
 * (`scripts/chipotle-adapter-proof.mjs`) needs. Run this after editing
 * `chipotle-action.js`; the proof fails loudly if the two ever drift.
 */
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const srcPath = fileURLToPath(new URL("../lib/key-release/chipotle-action.js", import.meta.url))
const outPath = fileURLToPath(new URL("../lib/key-release/chipotle-action-source.ts", import.meta.url))

const source = await readFile(srcPath, "utf8")

const out = `/**
 * Generated by `.trim() +
  " \`pnpm chipotle:generate-action-source\` from `chipotle-action.js` — do" +
  ` not hand-edit.
 *
 * Bundled as a string so the browser can submit it as the \`code\` fallback
 * for Lit's \`POST /lit_action\` on a cache miss — see \`chipotle.ts\`'s
 * \`invokeActionWithCacheMissRetry\` and docs/stories/H-69.md's amendments.
 * \`scripts/chipotle-adapter-proof.mjs\` asserts this constant stays
 * byte-identical to \`chipotle-action.js\` on disk.
 */
export const CHIPOTLE_ACTION_SOURCE = ${JSON.stringify(source)}
`

await writeFile(outPath, out)
console.log(`Wrote ${outPath} (${source.length} bytes)`)
